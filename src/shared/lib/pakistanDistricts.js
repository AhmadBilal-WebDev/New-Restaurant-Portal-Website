function normalizeName(value) {
  return value.toLowerCase().replace(/\s+district$/i, "").replace(/\s+tehsil$/i, "").replace(/\s+division$/i, "").replace(/\s+city$/i, "").replace(/[^a-z0-9\s]/g, " ").replace(/\s+/g, " ").trim();
}
function resolveDistrictForCity(cityName, districts) {
  const alias = CITY_TO_DISTRICT_ALIAS[cityName];
  if (alias && districts.some((d) => d.toLowerCase() === alias.toLowerCase())) {
    return districts.find((d) => d.toLowerCase() === alias.toLowerCase()) || alias;
  }
  const cityNorm = normalizeName(cityName);
  for (const district of districts) {
    const dNorm = normalizeName(district);
    if (cityNorm === dNorm) return district;
  }
  for (const district of districts) {
    const dNorm = normalizeName(district);
    if (cityNorm.startsWith(dNorm) || cityNorm.includes(` ${dNorm}`) || dNorm.includes(cityNorm)) {
      return district;
    }
  }
  return null;
}
