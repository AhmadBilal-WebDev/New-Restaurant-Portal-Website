function uniqueSorted(names) {
  const seen = /* @__PURE__ */ new Set();
  const out = [];
  for (const name of names) {
    const key = name.trim().toLowerCase();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(name.trim());
  }
  return out.sort((a, b) => a.localeCompare(b));
}
